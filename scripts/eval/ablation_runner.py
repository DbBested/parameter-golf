#!/usr/bin/env python3
"""Ablation framework for parameter-golf competition.

Supports toggling technique flags for systematic ablation studies,
submitting SLURM jobs with modified configs, and comparing results
with statistical significance testing.

Usage:
    # Dry-run ablation (shows what would be submitted):
    python ablation_runner.py --dry-run --technique bigram_hash \
        --result-dir experiments/results

    # Compare ablation results:
    python ablation_runner.py --compare \
        --result-dir experiments/results \
        --technique bigram_hash \
        --baseline-prefix baseline_seed \
        --ablation-prefix bigram_hash_seed
"""

import argparse
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

import numpy as np
from scipy.stats import ttest_ind


# Default baseline hyperparameters (from train_gpt.py Hyperparameters class)
DEFAULT_BASE_CONFIG = {
    "seed": 1337,
    "num_layers": 9,
    "model_dim": 512,
    "vocab_size": 1024,
    "num_heads": 8,
    "num_kv_heads": 4,
    "mlp_mult": 2,
    "iterations": 20000,
    "train_seq_len": 1024,
    "train_batch_tokens": 524288,
    "max_wallclock_seconds": 600,
    "matrix_lr": 0.04,
    "muon_momentum": 0.95,
}


def run_ablation(
    base_config,
    technique_name,
    technique_enabled,
    sbatch_template,
    submit_dir,
    dry_run=False,
    seeds=None,
):
    """Create and optionally submit a SLURM job for an ablation run.

    Args:
        base_config: dict of baseline hyperparameters.
        technique_name: string identifying the technique (e.g., "bigram_hash").
        technique_enabled: bool (True = with technique, False = without).
        sbatch_template: Path to the base SLURM sbatch file to modify.
        submit_dir: Working directory for job submission.
        dry_run: If True, print the command without submitting.
        seeds: List of seeds to run. Defaults to [1337, 42, 7].

    Returns:
        dict with job_id (or "dry_run"), config, technique_name, enabled.
    """
    if seeds is None:
        seeds = [1337, 42, 7]

    # Build environment variable overrides from config
    env_vars = {}
    for key, value in base_config.items():
        env_key = key.upper()
        env_vars[env_key] = str(value)

    # Set technique-specific environment variable
    technique_env_key = f"ENABLE_{technique_name.upper()}"
    env_vars[technique_env_key] = "1" if technique_enabled else "0"

    # Build run ID prefix
    prefix = f"{technique_name}_seed" if technique_enabled else f"no_{technique_name}_seed"

    # Create modified sbatch script
    env_exports = "\n".join(f'export {k}="{v}"' for k, v in sorted(env_vars.items()))

    modified_script = f"""#!/bin/bash
# Ablation run: {technique_name} {'ENABLED' if technique_enabled else 'DISABLED'}
# Auto-generated by ablation_runner.py

# Source the base sbatch template's SLURM headers
"""

    # Read and modify sbatch template
    with open(sbatch_template, "r") as f:
        template_lines = f.readlines()

    # Extract SBATCH headers
    sbatch_headers = []
    for line in template_lines:
        if line.startswith("#SBATCH"):
            # Override time for multi-seed
            if "--time=" in line:
                sbatch_headers.append("#SBATCH --time=02:00:00\n")
            elif "--job-name=" in line:
                sbatch_headers.append(f"#SBATCH --job-name=pgolf-ablation-{technique_name}\n")
            elif "--output=" in line:
                sbatch_headers.append(
                    f"#SBATCH --output=experiments/logs/%j-ablation-{technique_name}.out\n"
                )
            elif "--error=" in line:
                sbatch_headers.append(
                    f"#SBATCH --error=experiments/logs/%j-ablation-{technique_name}.err\n"
                )
            else:
                sbatch_headers.append(line)

    modified_script = "#!/bin/bash\n"
    modified_script += f"# Ablation: {technique_name} {'ENABLED' if technique_enabled else 'DISABLED'}\n"
    modified_script += "".join(sbatch_headers)
    modified_script += f"""
# Environment setup
module load miniforge/25.11.0-0 cuda/12.4.0 cudnn/9.8.0.87-cuda12
eval "$(conda shell.bash hook)"
conda activate pgolf

# Technique configuration
{env_exports}

echo "Ablation: {technique_name} = {'enabled' if technique_enabled else 'disabled'}"

cd "${{SLURM_SUBMIT_DIR}}/repo"

for SEED in {' '.join(str(s) for s in seeds)}; do
    export SEED=$SEED
    export RUN_ID="{prefix}${{SEED}}"
    echo "=== Running seed $SEED (run_id: $RUN_ID) ==="

    torchrun --standalone --nproc_per_node=8 train_gpt.py

    cd "${{SLURM_SUBMIT_DIR}}"

    # Log experiment
    python scripts/eval/process_baseline_results.py \\
        --log experiments/logs/${{SLURM_JOB_ID}}-ablation-{technique_name}.out \\
        --result-dir experiments/results \\
        --run-id "$RUN_ID" \\
        --seed $SEED

    cd "${{SLURM_SUBMIT_DIR}}/repo"
done

echo "Ablation complete: {technique_name}"
"""

    result = {
        "technique_name": technique_name,
        "enabled": technique_enabled,
        "config": base_config,
        "seeds": seeds,
        "run_id_prefix": prefix,
    }

    if dry_run:
        print(f"=== DRY RUN: Ablation {technique_name} ===")
        print(f"Technique: {technique_name}")
        print(f"Enabled: {technique_enabled}")
        print(f"Seeds: {seeds}")
        print(f"Run ID prefix: {prefix}")
        print(f"Environment overrides:")
        for k, v in sorted(env_vars.items()):
            print(f"  {k}={v}")
        print(f"\nGenerated script preview:")
        print(modified_script[:500] + "...")
        result["job_id"] = "dry_run"
        return result

    # Write and submit the script
    script_dir = Path(submit_dir) / "scripts" / "slurm"
    script_dir.mkdir(parents=True, exist_ok=True)
    script_path = script_dir / f"ablation_{technique_name}.sbatch"
    with open(script_path, "w") as f:
        f.write(modified_script)
    os.chmod(script_path, 0o755)

    try:
        proc = subprocess.run(
            ["sbatch", str(script_path)],
            cwd=submit_dir,
            capture_output=True,
            text=True,
        )
        if proc.returncode != 0:
            print(f"ERROR: sbatch failed: {proc.stderr}", file=sys.stderr)
            result["job_id"] = None
            return result

        # Parse job ID from sbatch output
        job_id = proc.stdout.strip().split()[-1]
        result["job_id"] = job_id
        print(f"Submitted ablation job {job_id} for {technique_name}")
    except FileNotFoundError:
        print("ERROR: sbatch command not found (not on SLURM cluster?)", file=sys.stderr)
        result["job_id"] = None

    return result


def compare_ablation_results(result_dir, baseline_prefix, ablation_prefix, technique_name=None):
    """Compare ablation results against baseline using t-test.

    Args:
        result_dir: Directory containing experiments.jsonl.
        baseline_prefix: Run ID prefix for baseline records.
        ablation_prefix: Run ID prefix for ablation records.
        technique_name: Optional technique name for display.

    Returns:
        dict with baseline_mean, ablation_mean, improvement, p_value,
        significant (bool at p<0.01).
    """
    log_path = Path(result_dir) / "experiments.jsonl"
    if not log_path.exists():
        print(f"ERROR: No experiments file at {log_path}", file=sys.stderr)
        return None

    baseline_bpb = []
    ablation_bpb = []

    with open(log_path) as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            try:
                record = json.loads(line)
            except json.JSONDecodeError:
                continue
            run_id = record.get("run_id", "")
            val_bpb = record.get("metrics", {}).get("val_bpb")
            if val_bpb is None:
                continue
            if run_id.startswith(baseline_prefix):
                baseline_bpb.append(float(val_bpb))
            elif run_id.startswith(ablation_prefix):
                ablation_bpb.append(float(val_bpb))

    if not baseline_bpb:
        print(f"ERROR: No baseline records for prefix '{baseline_prefix}'", file=sys.stderr)
        return None
    if not ablation_bpb:
        print(f"ERROR: No ablation records for prefix '{ablation_prefix}'", file=sys.stderr)
        return None

    baseline_mean = float(np.mean(baseline_bpb))
    ablation_mean = float(np.mean(ablation_bpb))
    improvement = baseline_mean - ablation_mean

    # Two-sample t-test: is ablation < baseline?
    t_stat, p_value = ttest_ind(ablation_bpb, baseline_bpb, alternative="less")

    significant = p_value < 0.01

    display_name = technique_name or ablation_prefix
    print(f"=== Ablation: {display_name} ===")
    print(f"Baseline mean BPB:  {baseline_mean:.4f} ({len(baseline_bpb)} seeds)")
    print(f"With technique:     {ablation_mean:.4f} ({len(ablation_bpb)} seeds)")
    print(f"Improvement:        {improvement:.4f}")
    print(f"t-statistic:        {t_stat:.4f}")
    print(f"p-value:            {p_value:.6f}")
    sig_str = "YES" if significant else "NO"
    print(f"Significant (p<0.01): {sig_str}")

    return {
        "technique_name": display_name,
        "baseline_mean": baseline_mean,
        "ablation_mean": ablation_mean,
        "improvement": improvement,
        "t_statistic": float(t_stat),
        "p_value": float(p_value),
        "significant": significant,
        "n_baseline": len(baseline_bpb),
        "n_ablation": len(ablation_bpb),
    }


def main():
    """CLI entry point for ablation runner."""
    parser = argparse.ArgumentParser(
        description="Ablation framework for parameter-golf techniques"
    )
    parser.add_argument(
        "--technique",
        required=True,
        help="Technique name (e.g., bigram_hash, muon, int6_qat)",
    )
    parser.add_argument(
        "--result-dir",
        default="experiments/results",
        help="Directory containing experiments.jsonl",
    )
    parser.add_argument(
        "--baseline-prefix",
        default="baseline_seed",
        help="Run ID prefix for baseline results",
    )
    parser.add_argument(
        "--ablation-prefix",
        default=None,
        help="Run ID prefix for ablation results (default: {technique}_seed)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="Print commands without submitting jobs",
    )
    parser.add_argument(
        "--compare",
        action="store_true",
        help="Compare existing ablation results against baseline",
    )
    parser.add_argument(
        "--sbatch-template",
        default="scripts/slurm/train_baseline.sbatch",
        help="Base SLURM script template",
    )
    parser.add_argument(
        "--submit-dir",
        default=".",
        help="Working directory for SLURM job submission",
    )

    args = parser.parse_args()

    ablation_prefix = args.ablation_prefix or f"{args.technique}_seed"

    if args.compare:
        result = compare_ablation_results(
            args.result_dir,
            args.baseline_prefix,
            ablation_prefix,
            technique_name=args.technique,
        )
        if result:
            print(f"\n--- JSON Output ---")
            print(json.dumps(result, indent=2))
        else:
            sys.exit(1)
    else:
        result = run_ablation(
            base_config=DEFAULT_BASE_CONFIG,
            technique_name=args.technique,
            technique_enabled=True,
            sbatch_template=args.sbatch_template,
            submit_dir=args.submit_dir,
            dry_run=args.dry_run,
        )
        print(f"\n--- JSON Output ---")
        print(json.dumps(result, indent=2))


if __name__ == "__main__":
    main()
